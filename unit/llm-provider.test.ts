describe("LLMFallbackChain", () => {
  it("returns primary provider result when it succeeds without calling fallback", async () => {
    let openAiCalled = false;
    const primary: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => true,
      generate: async () => ({
        text: "Groq post",
        model: "llama-3",
        provider: "groq",
        validation: validatePost("Bluesky", "Groq post"),
      }),
    };
    const secondary: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => {
        openAiCalled = true;
        return {
          text: "OpenAI post",
          model: "gpt-6-luna",
          provider: "openai",
          validation: validatePost("Bluesky", "OpenAI post"),
        };
      },
    };

    const chain = new LLMFallbackChain([primary, secondary]);
    const result = await chain.generate(mockInput);

    assert.equal(result.text, "Groq post");
    assert.equal(result.provider, "groq");
    assert.equal(openAiCalled, false);
  });

  it("falls back to OpenAI when Groq throws an error", async () => {
    const primary: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => true,
      generate: async () => {
        throw new PostGenerationError("Groq returned HTTP 500", "provider_error");
      },
    };
    const secondary: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => ({
        text: "OpenAI fallback post",
        model: "gpt-6-luna",
        provider: "openai",
        validation: validatePost("Bluesky", "OpenAI fallback post"),
      }),
    };

    const chain = new LLMFallbackChain([primary, secondary]);
    const result = await chain.generate(mockInput);

    assert.equal(result.text, "OpenAI fallback post");
    assert.equal(result.provider, "openai");
    assert.equal(result.model, "gpt-6-luna");
  });

  it("notifies onAttempt for failed attempts and subsequent fallback success", async () => {
    const attempts: Array<{ provider: string; status: string; errorCode?: string }> = [];
    const primary: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => true,
      generate: async () => {
        throw new PostGenerationError("Groq rate limited", "rate_limited");
      },
    };
    const secondary: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => ({
        text: "OpenAI post",
        model: "gpt-6-luna",
        provider: "openai",
        validation: validatePost("Bluesky", "OpenAI post"),
      }),
    };

    const chain = new LLMFallbackChain([primary, secondary], (attempt) => {
      attempts.push({
        provider: attempt.provider,
        status: attempt.status,
        errorCode: attempt.errorCode,
      });
    });

    const result = await chain.generate(mockInput);
    assert.equal(result.provider, "openai");
    assert.equal(attempts.length, 2);
    assert.deepEqual(attempts[0], {
      provider: "groq",
      status: "error",
      errorCode: "rate_limited",
    });
    assert.deepEqual(attempts[1], {
      provider: "openai",
      status: "success",
      errorCode: undefined,
    });
  });

  it("falls back to deterministic generator when both Groq and OpenAI fail", async () => {
    const primary: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => true,
      generate: async () => {
        throw new PostGenerationError("Groq down", "provider_error");
      },
    };
    const secondary: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => {
        throw new PostGenerationError("OpenAI down", "provider_error");
      },
    };

    const chain = new LLMFallbackChain([primary, secondary]);
    const result = await chain.generate(mockInput);

    assert.equal(result.model, "fallback");
    assert.equal(result.provider, "fallback");
    assert.equal(result.validation.valid, true);
  });

  it("skips unconfigured providers in the chain", async () => {
    let unconfiguredCalled = false;
    const unconfigured: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => false,
      generate: async () => {
        unconfiguredCalled = true;
        throw new Error("Should not be called");
      },
    };
    const configured: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => ({
        text: "Configured provider result",
        model: "gpt-6-luna",
        provider: "openai",
        validation: validatePost("Bluesky", "Configured provider result"),
      }),
    };

    const chain = new LLMFallbackChain([unconfigured, configured]);
    const result = await chain.generate(mockInput);

    assert.equal(unconfiguredCalled, false);
    assert.equal(result.text, "Configured provider result");
    assert.equal(result.provider, "openai");
  });

  it("createDefaultLLMChain constructs working chain with overrides", async () => {
    const fetchImpl: typeof fetch = async () => jsonResponse("Generated text from custom override");
    const chain = createDefaultLLMChain({
      groqApiKey: "override-key",
      groqModel: "override-model",
      openAiApiKey: "override-openai-key",
      openAiModel: "gpt-6-luna",
    });

    const result = await chain.generate(mockInput, fetchImpl);
    assert.equal(result.text, "Generated text from custom override");
    assert.equal(result.provider, "groq");
  });

  it("buildMessages tailors prompt for personal account vs association and adds LinkedIn host gratitude", () => {
    const personalInput: PostGenerationInput = {
      ...mockInput,
      accountName: "Personal",
      accountKind: "Personal",
      network: "LinkedIn",
      language: "es",
      reminderDays: 14,
    };

    const personalMessages = buildMessages(personalInput);
    const personalSystem = personalMessages[0].content;
    assert.match(personalSystem, /speaker participating in this event/);
    assert.match(personalSystem, /Inspect the event description/);
    assert.match(personalSystem, /talk title/);
    assert.match(personalSystem, /Tone: Must sound authentic, organic, genuinely enthusiastic/);
    assert.match(personalSystem, /🍺🍕/);
    assert.match(personalSystem, /dentro de dos semanas/);

    const associationInput: PostGenerationInput = {
      ...mockInput,
      accountName: "Barcelona JUG",
      accountKind: "Asociación",
      network: "X",
      language: "es",
      reminderDays: 7,
    };
    const assocMessages = buildMessages(associationInput);
    const assocSystem = assocMessages[0].content;
    assert.match(assocSystem, /community\/association organizing team/);
    assert.doesNotMatch(assocSystem, /🍺🍕/);
    assert.match(assocSystem, /dentro de una semana/);
  });

  it("buildFallbackDraftText includes formatted date, time, and personal/association perspective", () => {
    const personalFallback = buildFallbackDraftText({
      ...mockInput,
      accountName: "Personal",
      accountKind: "Personal",
      network: "LinkedIn",
      language: "es",
      reminderDays: 14,
    });
    assert.match(personalFallback, /¡Participo dentro de dos semanas en Community Night!/);
    assert.match(personalFallback, /12\/11\/2026/);
    assert.match(personalFallback, /19:00/);
    assert.match(personalFallback, /🍺🍕/);

    const assocFallback = buildFallbackDraftText({
      ...mockInput,
      accountName: "Barcelona JUG",
      accountKind: "Asociación",
      network: "Bluesky",
      language: "en",
      reminderDays: 1,
    });
    assert.match(assocFallback, /Join us tomorrow for Community Night/);
    assert.match(assocFallback, /12\/11\/2026/);
    assert.match(assocFallback, /19:00/);
    assert.doesNotMatch(assocFallback, /🍺🍕/);
  });

  it("filters and orders Groq models by lowest cost while excluding non-chat and low-capacity models", () => {
    const models: GroqModelEntry[] = [
      { id: "whisper-large-v3", active: true, input_modalities: ["audio"], output_modalities: ["transcription"] },
      { id: "canopylabs/orpheus-v1-english", active: true, input_modalities: ["text"], output_modalities: ["speech"] },
      { id: "meta-llama/llama-prompt-guard-2-86m", active: true, context_window: 512, max_completion_tokens: 512 },
      { id: "openai/gpt-oss-safeguard-20b", active: true, context_window: 131072, max_completion_tokens: 65536 },
      { id: "allam-2-7b", active: true, context_window: 4096, max_completion_tokens: 4096 },
      { id: "inactive-model", active: false, context_window: 131072, max_completion_tokens: 16384 },
      { id: "audio-only-input", active: true, input_modalities: ["audio"], output_modalities: ["text"], context_window: 16384 },
      {
        id: "qwen/qwen3.8-27b",
        active: true,
        context_window: 131072,
        max_completion_tokens: 16384,
        input_modalities: ["text", "image"],
        output_modalities: ["text"],
        pricing: { prompt: "0.0000008", completion: "0.000004" },
        supported_features: ["reasoning"],
      },
      {
        id: "openai/gpt-oss-120b",
        active: true,
        context_window: 131072,
        max_completion_tokens: 65536,
        input_modalities: ["text"],
        output_modalities: ["text"],
        pricing: { prompt: "0.00000015", completion: "0.0000006" },
        supported_features: ["reasoning"],
      },
      {
        id: "openai/gpt-oss-20b",
        active: true,
        context_window: 131072,
        max_completion_tokens: 65536,
        input_modalities: ["text"],
        output_modalities: ["text"],
        pricing: { prompt: "0.000000075", completion: "0.0000003" },
        supported_features: ["reasoning"],
      },
      {
        id: "unpriced-chat-model",
        active: true,
        context_window: 32768,
        max_completion_tokens: 8192,
      },
    ];

    assert.equal(isEligibleGroqChatModel(models[0]), false);
    assert.equal(isEligibleGroqChatModel(models[1]), false);
    assert.equal(isEligibleGroqChatModel(models[2]), false);
    assert.equal(isEligibleGroqChatModel(models[3]), false);
    assert.equal(isEligibleGroqChatModel(models[4]), false);
    assert.equal(isEligibleGroqChatModel(models[5]), false);
    assert.equal(isEligibleGroqChatModel(models[6]), false);
    assert.equal(computeGroqModelCostScore({ id: "zero-cost", pricing: { prompt: "0", completion: "0" } }), Number.POSITIVE_INFINITY);

    const selected = selectGroqCandidateModels(models);
    assert.deepEqual(
      selected.map((m) => m.id),
      ["openai/gpt-oss-20b", "openai/gpt-oss-120b", "qwen/qwen3.8-27b"],
    );
    assert.equal(isReasoningModel(selected[0]), true);
    assert.equal(isReasoningModel({ id: "openai/gpt-oss-20b" }), true);
    assert.equal(isReasoningModel({ id: "llama-3.1-8b-instant" }), false);
    assert.equal(supportsLowReasoningEffort({ id: "openai/gpt-oss-20b" }), true);
    assert.equal(supportsLowReasoningEffort({ id: "qwen/qwen3.8-27b" }), false);

    // Fallback to known pricing when API omits pricing, and tie-break unpriced models by ID
    const unpricedOrdered = selectGroqCandidateModels([
      { id: "z-unknown-model", active: true, context_window: 32768, max_completion_tokens: 8192 },
      { id: "a-unknown-model", active: true, context_window: 32768, max_completion_tokens: 8192 },
      { id: "openai/gpt-oss-20b", active: true, context_window: 131072, max_completion_tokens: 65536 },
    ]);
    assert.deepEqual(
      unpricedOrdered.map((m) => m.id),
      ["openai/gpt-oss-20b", "a-unknown-model", "z-unknown-model"],
    );
  });

  it("discovers Groq models from /openai/v1/models and retries next candidate on output_truncated", async () => {
    const calledModels: Array<{ model: string; reasoning_effort?: string; max_completion_tokens?: number }> = [];
    const attempts: Array<{ provider: string; model: string; status: string; errorCode?: string; completionTokens?: number }> = [];

    const fetchImpl: typeof fetch = async (url, init) => {
      if (String(url) === GROQ_MODELS_URL) {
        return new Response(
          JSON.stringify({
            object: "list",
            data: [
              {
                id: "openai/gpt-oss-20b",
                active: true,
                context_window: 131072,
                max_completion_tokens: 65536,
                input_modalities: ["text"],
                output_modalities: ["text"],
                pricing: { prompt: "0.000000075", completion: "0.0000003" },
                supported_features: ["reasoning"],
              },
              {
                id: "qwen/qwen3.8-27b",
                active: true,
                context_window: 131072,
                max_completion_tokens: 16384,
                input_modalities: ["text"],
                output_modalities: ["text"],
                pricing: { prompt: "0.0000008", completion: "0.000004" },
                supported_features: ["reasoning"],
              },
            ],
          }),
          { status: 200 },
        );
      }

      const body = JSON.parse(String(init?.body)) as {
        model: string;
        reasoning_effort?: string;
        max_completion_tokens?: number;
      };
      calledModels.push(body);

      if (body.model === "openai/gpt-oss-20b") {
        return new Response(
          JSON.stringify({
            choices: [{ finish_reason: "length", message: { content: "" } }],
            usage: { prompt_tokens: 400, completion_tokens: 4096, total_tokens: 4496 },
          }),
          { status: 200 },
        );
      }

      return new Response(
        JSON.stringify({
          choices: [{ finish_reason: "stop", message: { content: "Recovered with second Groq model!" } }],
          usage: { prompt_tokens: 400, completion_tokens: 80, total_tokens: 480 },
        }),
        { status: 200 },
      );
    };

    const chain = createDefaultLLMChain(
      { groqApiKey: "gsk-key", groqModel: "" },
      (attempt) => {
        attempts.push({
          provider: attempt.provider,
          model: attempt.model,
          status: attempt.status,
          errorCode: attempt.errorCode,
          completionTokens: attempt.completionTokens,
        });
      },
    );

    const result = await chain.generate(mockInput, fetchImpl);
    assert.equal(result.text, "Recovered with second Groq model!");
    assert.equal(result.model, "qwen/qwen3.8-27b");
    assert.equal(result.provider, "groq");
    assert.equal(calledModels.length, 2);
    assert.equal(calledModels[0].model, "openai/gpt-oss-20b");
    assert.equal(calledModels[0].reasoning_effort, "low");
    assert.equal(calledModels[0].max_completion_tokens, 4096);
    assert.equal(calledModels[1].model, "qwen/qwen3.8-27b");
    assert.equal(calledModels[1].reasoning_effort, undefined);
    assert.equal(calledModels[1].max_completion_tokens, 4096);
    assert.equal(attempts.length, 2);
    assert.deepEqual(attempts[0], {
      provider: "groq",
      model: "openai/gpt-oss-20b",
      status: "error",
      errorCode: "output_truncated",
      completionTokens: 4096,
    });
    assert.deepEqual(attempts[1], {
      provider: "groq",
      model: "qwen/qwen3.8-27b",
      status: "success",
      errorCode: undefined,
      completionTokens: 80,
    });
  });

  it("falls back to configured or default model when /openai/v1/models fails transiently", async () => {
    const fetchImpl: typeof fetch = async (url) => {
      if (String(url) === GROQ_MODELS_URL) {
        return new Response("Models endpoint down", { status: 503 });
      }
      return new Response(
        JSON.stringify({
          choices: [{ finish_reason: "stop", message: { content: "Generated via fallback model after discovery 503" } }],
        }),
        { status: 200 },
      );
    };

    const chain = createDefaultLLMChain({ groqApiKey: "gsk-key", groqModel: "" });
    const result = await chain.generate(mockInput, fetchImpl);
    assert.equal(result.provider, "groq");
    assert.equal(result.model, "openai/gpt-oss-20b");
    assert.equal(result.text, "Generated via fallback model after discovery 503");
  });

  it("preserves model name and token usage in error attempt when all Groq candidates truncate", async () => {
    const attempts: Array<{ provider: string; model: string; status: string; errorCode?: string; completionTokens?: number }> = [];
    const fetchImpl: typeof fetch = async (url) => {
      if (String(url) === GROQ_MODELS_URL) {
        return new Response(
          JSON.stringify({
            object: "list",
            data: [
              {
                id: "openai/gpt-oss-20b",
                active: true,
                context_window: 131072,
                max_completion_tokens: 65536,
                pricing: { prompt: "0.000000075", completion: "0.0000003" },
                supported_features: ["reasoning"],
              },
            ],
          }),
          { status: 200 },
        );
      }
      return new Response(
        JSON.stringify({
          choices: [{ finish_reason: "length", message: { content: "" } }],
          usage: { prompt_tokens: 450, completion_tokens: 4096, total_tokens: 4546 },
        }),
        { status: 200 },
      );
    };

    const chain = createDefaultLLMChain(
      { groqApiKey: "gsk-key", groqModel: "", openAiApiKey: "" },
      (attempt) => {
        attempts.push({
          provider: attempt.provider,
          model: attempt.model,
          status: attempt.status,
          errorCode: attempt.errorCode,
          completionTokens: attempt.completionTokens,
        });
      },
    );

    const result = await chain.generate(mockInput, fetchImpl);
    assert.equal(result.provider, "fallback");
    assert.equal(result.generationError, "output_truncated");
    assert.equal(attempts[0].provider, "groq");
    assert.equal(attempts[0].model, "openai/gpt-oss-20b");
    assert.equal(attempts[0].errorCode, "output_truncated");
    assert.equal(attempts[0].completionTokens, 4096);
  });
});
