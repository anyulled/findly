import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  OpenAICompatibleProvider,
  DeterministicFallbackProvider,
  LLMFallbackChain,
  createDefaultLLMChain,
  buildMessages,
  buildFallbackDraftText,
  type LLMProvider,
} from "../src/lib/llm-provider";
import { PostGenerationError, type PostGenerationInput } from "../src/lib/groq";
import { validatePost } from "../src/lib/social-validation";

const mockInput: PostGenerationInput = {
  accountId: "acc-1",
  accountName: "BarcelonaJS",
  accountVoice: "Warm, informal, and welcoming.",
  network: "Bluesky",
  language: "en",
  event: {
    title: "Community Night",
    date: "2026-11-12",
    time: "19:00",
    place: "Barcelona",
    description: "Meet local developers and share ideas.",
    url: "https://example.org/event",
  },
  reminderDays: 7,
};

function jsonResponse(content: unknown, status = 200): Response {
  return new Response(JSON.stringify({ choices: [{ message: { content } }] }), { status });
}

describe("OpenAICompatibleProvider", () => {
  it("reports isConfigured correctly based on API key and model", () => {
    const unconfigured = new OpenAICompatibleProvider(
      "test",
      "Test",
      "https://api.test.com",
      () => undefined,
      () => undefined,
    );
    assert.equal(unconfigured.isConfigured(), false);

    const missingModel = new OpenAICompatibleProvider(
      "test",
      "Test",
      "https://api.test.com",
      () => "key",
      () => "   ",
    );
    assert.equal(missingModel.isConfigured(), false);

    const configured = new OpenAICompatibleProvider(
      "test",
      "Test",
      "https://api.test.com",
      () => "key",
      () => "model-x",
    );
    assert.equal(configured.isConfigured(), true);
  });

  it("throws not_configured error if generate is called without credentials", async () => {
    const provider = new OpenAICompatibleProvider(
      "test",
      "Test Provider",
      "https://api.test.com",
      () => "",
      () => "",
    );
    await assert.rejects(provider.generate(mockInput), {
      code: "not_configured",
      message: "Test Provider API key and model must be configured on the server.",
    });
  });

  it("sends requests to configured endpoint and returns generated post", async () => {
    let capturedUrl = "";
    let capturedAuth = "";
    let capturedBody: Record<string, unknown> = {};
    const fetchImpl: typeof fetch = async (url, init) => {
      capturedUrl = String(url);
      capturedAuth = new Headers(init?.headers).get("authorization") ?? "";
      capturedBody = JSON.parse(String(init?.body)) as Record<string, unknown>;
      return jsonResponse("Valid post generated by OpenAI compatible provider");
    };

    const provider = new OpenAICompatibleProvider(
      "openai",
      "OpenAI",
      "https://api.openai.com/v1/chat/completions",
      () => "sk-mock-key",
      () => "gpt-6-luna",
    );

    const result = await provider.generate(mockInput, fetchImpl);
    assert.equal(result.text, "Valid post generated by OpenAI compatible provider");
    assert.equal(result.provider, "openai");
    assert.equal(result.model, "gpt-6-luna");
    assert.equal(result.validation.valid, true);
    assert.equal(capturedUrl, "https://api.openai.com/v1/chat/completions");
    assert.equal(capturedAuth, "Bearer sk-mock-key");
    assert.equal(capturedBody.max_completion_tokens, 1500);
    assert.equal(capturedBody.temperature, undefined);
  });

  it("handles empty and unreadable responses safely", async () => {
    const emptyProvider = new OpenAICompatibleProvider(
      "test",
      "Test",
      "https://api.test.com",
      () => "key",
      () => "model",
    );
    const emptyFetch: typeof fetch = async () => jsonResponse("   ");
    await assert.rejects(emptyProvider.generate(mockInput, emptyFetch), {
      code: "empty_response",
    });

    const malformedFetch: typeof fetch = async () => new Response("not-json", { status: 200 });
    await assert.rejects(emptyProvider.generate(mockInput, malformedFetch), {
      code: "provider_error",
    });
  });

  it("masks network details on error and rejects over-limit posts", async () => {
    const provider = new OpenAICompatibleProvider(
      "test",
      "Test",
      "https://api.test.com",
      () => "key",
      () => "model",
    );
    const networkFailFetch: typeof fetch = async () => { throw new Error("DNS resolution failure"); };
    await assert.rejects(provider.generate(mockInput, networkFailFetch), (err: Error) => {
      return err instanceof PostGenerationError && !err.message.includes("DNS resolution failure");
    });

    const overLimitFetch: typeof fetch = async () => jsonResponse("x".repeat(350));
    await assert.rejects(provider.generate(mockInput, overLimitFetch), {
      code: "over_limit",
    });
  });
});

describe("DeterministicFallbackProvider", () => {
  it("always reports configured and returns fallback post", async () => {
    const provider = new DeterministicFallbackProvider();
    assert.equal(provider.isConfigured(), true);
    const result = await provider.generate(mockInput);
    assert.equal(result.model, "fallback");
    assert.equal(result.provider, "fallback");
    assert.equal(result.validation.valid, true);
    assert.match(result.text, /Community Night/u);
  });
});

describe("LLMFallbackChain", () => {
  it("returns primary provider result when it succeeds without calling fallback", async () => {
    let openAiCalled = false;
    const primary: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => true,
      generate: async () => ({
        text: "Groq post",
        model: "llama-3",
        provider: "groq",
        validation: validatePost("Bluesky", "Groq post"),
      }),
    };
    const secondary: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => {
        openAiCalled = true;
        return {
          text: "OpenAI post",
          model: "gpt-6-luna",
          provider: "openai",
          validation: validatePost("Bluesky", "OpenAI post"),
        };
      },
    };

    const chain = new LLMFallbackChain([primary, secondary]);
    const result = await chain.generate(mockInput);

    assert.equal(result.text, "Groq post");
    assert.equal(result.provider, "groq");
    assert.equal(openAiCalled, false);
  });

  it("falls back to OpenAI when Groq throws an error", async () => {
    const primary: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => true,
      generate: async () => {
        throw new PostGenerationError("Groq returned HTTP 500", "provider_error");
      },
    };
    const secondary: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => ({
        text: "OpenAI fallback post",
        model: "gpt-6-luna",
        provider: "openai",
        validation: validatePost("Bluesky", "OpenAI fallback post"),
      }),
    };

    const chain = new LLMFallbackChain([primary, secondary]);
    const result = await chain.generate(mockInput);

    assert.equal(result.text, "OpenAI fallback post");
    assert.equal(result.provider, "openai");
    assert.equal(result.model, "gpt-6-luna");
  });

  it("falls back to deterministic generator when both Groq and OpenAI fail", async () => {
    const primary: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => true,
      generate: async () => {
        throw new PostGenerationError("Groq down", "provider_error");
      },
    };
    const secondary: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => {
        throw new PostGenerationError("OpenAI down", "provider_error");
      },
    };

    const chain = new LLMFallbackChain([primary, secondary]);
    const result = await chain.generate(mockInput);

    assert.equal(result.model, "fallback");
    assert.equal(result.provider, "fallback");
    assert.equal(result.validation.valid, true);
  });

  it("skips unconfigured providers in the chain", async () => {
    let unconfiguredCalled = false;
    const unconfigured: LLMProvider = {
      id: "groq",
      name: "Groq",
      isConfigured: () => false,
      generate: async () => {
        unconfiguredCalled = true;
        throw new Error("Should not be called");
      },
    };
    const configured: LLMProvider = {
      id: "openai",
      name: "OpenAI",
      isConfigured: () => true,
      generate: async () => ({
        text: "Configured provider result",
        model: "gpt-6-luna",
        provider: "openai",
        validation: validatePost("Bluesky", "Configured provider result"),
      }),
    };

    const chain = new LLMFallbackChain([unconfigured, configured]);
    const result = await chain.generate(mockInput);

    assert.equal(unconfiguredCalled, false);
    assert.equal(result.text, "Configured provider result");
    assert.equal(result.provider, "openai");
  });

  it("createDefaultLLMChain constructs working chain with overrides", async () => {
    const fetchImpl: typeof fetch = async () => jsonResponse("Generated text from custom override");
    const chain = createDefaultLLMChain({
      groqApiKey: "override-key",
      groqModel: "override-model",
      openAiApiKey: "override-openai-key",
      openAiModel: "gpt-6-luna",
    });

    const result = await chain.generate(mockInput, fetchImpl);
    assert.equal(result.text, "Generated text from custom override");
    assert.equal(result.provider, "groq");
  });

  it("buildMessages tailors prompt for personal account vs association and adds LinkedIn host gratitude", () => {
    const personalInput: PostGenerationInput = {
      ...mockInput,
      accountName: "Personal",
      accountKind: "Personal",
      network: "LinkedIn",
      language: "es",
      reminderDays: 14,
    };

    const personalMessages = buildMessages(personalInput);
    const personalSystem = personalMessages[0].content;
    assert.match(personalSystem, /speaker participating in this event/);
    assert.match(personalSystem, /Inspect the event description/);
    assert.match(personalSystem, /talk title/);
    assert.match(personalSystem, /Tone: Must sound authentic, organic, genuinely enthusiastic/);
    assert.match(personalSystem, /🍺🍕/);
    assert.match(personalSystem, /dentro de dos semanas/);

    const associationInput: PostGenerationInput = {
      ...mockInput,
      accountName: "Barcelona JUG",
      accountKind: "Asociación",
      network: "X",
      language: "es",
      reminderDays: 7,
    };
    const assocMessages = buildMessages(associationInput);
    const assocSystem = assocMessages[0].content;
    assert.match(assocSystem, /community\/association organizing team/);
    assert.doesNotMatch(assocSystem, /🍺🍕/);
    assert.match(assocSystem, /dentro de una semana/);
  });

  it("buildFallbackDraftText includes formatted date, time, and personal/association perspective", () => {
    const personalFallback = buildFallbackDraftText({
      ...mockInput,
      accountName: "Personal",
      accountKind: "Personal",
      network: "LinkedIn",
      language: "es",
      reminderDays: 14,
    });
    assert.match(personalFallback, /¡Participo dentro de dos semanas en Community Night!/);
    assert.match(personalFallback, /12\/11\/2026/);
    assert.match(personalFallback, /19:00/);
    assert.match(personalFallback, /🍺🍕/);

    const assocFallback = buildFallbackDraftText({
      ...mockInput,
      accountName: "Barcelona JUG",
      accountKind: "Asociación",
      network: "Bluesky",
      language: "en",
      reminderDays: 1,
    });
    assert.match(assocFallback, /Join us tomorrow for Community Night/);
    assert.match(assocFallback, /12\/11\/2026/);
    assert.match(assocFallback, /19:00/);
    assert.doesNotMatch(assocFallback, /🍺🍕/);
  });
});
